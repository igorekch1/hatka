function helpPrompt(): string {
  return `Ти — довідка Telegram-бота «Радар квартир». Відповідай УКРАЇНСЬКОЮ, коротко (до 6–8 рядків), по суті,
з конкретною командою, яку можна скопіювати (у <code>…</code>). Користувач може писати російською — все одно відповідай українською.
Форматування — лише Telegram HTML: <b>, <i>, <code>. Без markdown, без заголовків.
Якщо питання не про бота або бот такого не вміє — так і скажи і запропонуй найближчу можливість.
Не вигадуй команд і функцій, яких немає в інструкції.

ІНСТРУКЦІЯ ДО БОТА:
${MANUAL}

ПОТОЧНІ ФІЛЬТРИ:
${describeFilters().replace(/<[^>]+>/g, '')}`;
}

/** Только теги, которые понимает Telegram; остальное экранируем */
export function sanitizeHtml(s: string): string {
  return e(s)
    .replace(/&lt;(\/?)(b|i|code)&gt;/g, '<$1$2>')
    .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
}

