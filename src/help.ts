export async function answerHelp(question: string): Promise<Reply> {
  if (!question.trim()) return aiEnabled() ? { text: HELP_INTRO, ask: 'help' } : STATIC_HELP;
  if (!aiEnabled()) return STATIC_HELP;
  try {
    const answer = await callClaude(helpPrompt(), question.slice(0, 1000), 600);
    return {
      text: sanitizeHtml(answer.trim()) || 'Не зміг відповісти 😕',
      buttons: [[{ text: '❓ Ще питання', data: 'm:help' }, { text: '🏠 Меню', data: 'm:menu' }]],
    };
  } catch (err) {
    log('Help: ошибка ИИ', String(err));
    return STATIC_HELP;
  }
}
